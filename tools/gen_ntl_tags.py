#!/usr/bin/env python3
"""Build the NTL tag atlas + C table from the NTL mod (ntlmod-pub).

usage: python3 tools/gen_ntl_tags.py <path-to-ntlmod-pub>

writes app/res/textures/ntl_tags.png and app/src/game/ntl_tags_data.h
Tag ids follow the NTL mod: built-in t_0..t_59 -> id 0..59,
public fstags[i] -> id 200+i (i<168) or 500+i (i>=168).
"""
import base64, io, json, re, sys, os
from PIL import Image

src = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
js = open(os.path.join(src, "main-mt.js"), encoding="utf-8").read()
i = js.find('t_"+i+".webp"')
j = js.rfind('P="', 0, i)
builtin = js[j + 3: js.find('";', j)].replace(" ", "").split(":")
assert len(builtin) == 60, len(builtin)
fs = open(os.path.join(src, "fstags.js"), encoding="utf-8").read()
m = re.match(r"window\.fstags=JSON\.parse\('(.*)'\);?\s*$", fs, re.S)
fst = json.loads(m.group(1).replace("\\'", "'"))

tags = []  # (id, w, h, bx, by, c1, c2, PIL image)
for n, row in enumerate(builtin):
    w, h, c1, c2, bx, by = row.split(";")
    im = Image.open(os.path.join(src, "s", f"t_{n}.webp")).convert("RGBA")
    tags.append((n, int(w), int(h), int(bx), int(by), c1, c2, im))
for n, t in enumerate(fst):
    raw = base64.b64decode(t["fst_src"].split(",", 1)[1])
    im = Image.open(io.BytesIO(raw)).convert("RGBA")
    tid = 200 + n if n < 168 else 500 + n
    tags.append((tid, int(t["fst_blbw"]), int(t["fst_blbh"]), int(t["fst_blbx"]),
                 int(t["fst_blby"]), t["fst_atc1"], t["fst_atc2"], im))

# shelf packing, 2px gutter (transparent) so linear filtering never bleeds
AW, PAD = 2048, 4
order = sorted(range(len(tags)), key=lambda k: -tags[k][7].size[1])
pos = {}
x = y = rowh = 0
for k in order:
    w, h = tags[k][7].size
    if x + w + PAD > AW:
        x, y, rowh = 0, y + rowh + PAD, 0
    pos[k] = (x, y)
    x += w + PAD
    rowh = max(rowh, h)
AH = 1
while AH < y + rowh + PAD:
    AH *= 2
atlas = Image.new("RGBA", (AW, AH), (0, 0, 0, 0))
for k, (px, py) in pos.items():
    atlas.paste(tags[k][7], (px, py))
out_png = os.path.join(root, "app/res/textures/ntl_tags.png")
atlas.save(out_png, optimize=True)

CSS = {"red": "FF0000", "yellow": "FFFF00", "white": "FFFFFF", "black": "000000"}

def col(c):
    """CSS colour (#rrggbb, #rgb or a name used by the NTL mod) -> 0xRRGGBB."""
    h = CSS.get(c.lower(), c.lstrip("#"))
    if len(h) == 3:
        h = "".join(ch * 2 for ch in h)
    assert len(h) == 6 and int(h, 16) >= 0, c
    return "0x" + h.upper()

lines = ["/* GENERATED by tools/gen_ntl_tags.py -- do not edit by hand. */",
         "#ifndef NTL_TAGS_DATA_H", "#define NTL_TAGS_DATA_H", "",
         f"#define NTL_TAG_ATLAS_W {AW}", f"#define NTL_TAG_ATLAS_H {AH}",
         f"#define NTL_TAG_COUNT {len(tags)}", "",
         "typedef struct {", "  short id;          /* NTL tag id (what the server/join packet uses) */",
         "  short w, h;        /* draw size before scaling (NTL BI[].w/h) */",
         "  short bx, by;      /* draw offset from the antenna tip */",
         "  unsigned int c1, c2; /* antenna outer / inner colour 0xRRGGBB */",
         "  short ax, ay, aw, ah; /* pixel rect inside the atlas */",
         "} ntl_tag_def;", "", "static const ntl_tag_def ntl_tag_defs[NTL_TAG_COUNT] = {"]
for k, t in enumerate(tags):
    px, py = pos[k]
    lines.append("  {%d,%d,%d,%d,%d,%s,%s,%d,%d,%d,%d}," % (
        t[0], t[1], t[2], t[3], t[4], col(t[5]), col(t[6]), px, py, t[7].size[0], t[7].size[1]))
lines += ["};", "", "#endif", ""]
open(os.path.join(root, "app/src/game/ntl_tags_data.h"), "w").write("\n".join(lines))
print("tags", len(tags), "atlas", AW, AH, os.path.getsize(out_png) // 1024, "KB")
